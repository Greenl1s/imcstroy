#!/bin/sh
# Прогоняет все наборы. Перед каждым сервисы перезапускаются:
# у входа стоит защита от перебора (10 попыток за 5 минут с адреса),
# а проверки смены пароля делают несколько настоящих входов подряд.
# Счётчик попыток живёт в памяти процесса, поэтому перезапуск его и сбрасывает.
# Схема: разворачивается ли база с нуля. Отдельно от остальных — этому
# набору сервисы не нужны, он работает с чистой базой.
printf '%-14s %s\n' "db-fresh:" "$(bash "$(dirname "$0")/db-fresh.test.sh" 2>&1 | tail -1)"

for t in api linked-file user-delete ui; do
  sh "$(dirname "$0")/up.sh" > /dev/null 2>&1
  sleep 6
  printf '%-14s %s\n' "$t:" "$(node "$(dirname "$0")/$t.test.mjs" 2>&1 | tail -1)"
done
