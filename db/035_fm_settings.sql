-- ============================================================
--  Настройки, которые правит администратор из панели ИСУ.
--
--  Ключ-значение, а не колонка на каждую настройку: настроек будет
--  становиться больше, и заводить миграцию ради каждой галочки —
--  значит не заводить её вовсе и оставить всё в .env, как было.
--
--  Строка появляется здесь только тогда, когда администратор задал
--  значение сам. Пусто в таблице — значит работает то, что записано
--  в .env, а если и там пусто — умолчание из кода. Поэтому система,
--  где эту таблицу только что создали, ведёт себя ровно как раньше.
-- ============================================================

CREATE TABLE IF NOT EXISTS fm_settings (
  key        text PRIMARY KEY,
  value      text,
  -- Кто и когда менял: настройки задевают всех, и вопрос «кто это
  -- поставил» возникает раньше, чем вопрос «что поставили».
  updated_by integer REFERENCES users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
