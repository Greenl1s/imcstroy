-- ============================================================
--  Имя сотрудника отдельно от логина.
--
--  До сих пор у человека было одно-единственное имя — логин: им он
--  входил в систему, им же он значился в журнале, в задачах и в
--  «Учёте оборудования». Из-за этого логин нельзя было сделать
--  коротким служебным словом: его видели все.
--
--  Теперь их двое:
--    username  — то, что набирают при входе. Видит администратор и сам
--                хозяин учётной записи.
--    full_name — то, как человека зовут. Видно всем и везде.
--
--  ВАЖНО ПРО ОБНОВЛЕНИЕ: имя заполняется текущим логином. Это нарочно.
--  На сервере, который просто обновили, всё должно выглядеть ровно так
--  же, как выглядело вчера, — включая столбец «Специалисты / Эксперты»
--  в проектах, где имена записаны ТЕКСТОМ. Если бы имя осталось пустым,
--  система показывала бы людей без имени, а записанные в проектах
--  специалисты перестали бы совпадать со списком.
--
--  Единственности имени база не требует специально: её проверяет код и
--  объясняет, с кем совпало. Индекс здесь мог бы не создаться на живой
--  базе (например, два логина отличаются только регистром) и оборвать
--  миграцию на середине — а обрывать её нельзя.
-- ============================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS full_name text;

UPDATE users
   SET full_name = username
 WHERE full_name IS NULL OR btrim(full_name) = '';

-- Календарь берёт имена из вида, а не из запроса: пересобираем и его.
-- Набор столбцов тот же (owner_name, guests) — меняется только то, что
-- в них кладётся, поэтому CREATE OR REPLACE проходит без пересоздания.
--
-- Под условием нарочно: если календарь на этой базе ещё не заводили
-- (не накатывали 034), миграция должна спокойно пройти мимо, а не
-- оборваться на середине, оставив имя заполненным наполовину.
DO $$
BEGIN
  IF to_regclass('public.cal_events') IS NULL THEN
    RAISE NOTICE 'Календаря на этой базе нет — вид cal_events_view пропущен';
    RETURN;
  END IF;

  EXECUTE $view$
CREATE OR REPLACE VIEW cal_events_view AS
SELECT
  e.*,
  COALESCE(NULLIF(btrim(u.full_name), ''), u.username) AS owner_name,
  COALESCE(
    (SELECT json_agg(
              json_build_object(
                'id', g.user_id,
                'name', COALESCE(NULLIF(btrim(gu.full_name), ''), gu.username)
              )
              ORDER BY COALESCE(NULLIF(btrim(gu.full_name), ''), gu.username))
       FROM cal_event_guests g
       JOIN users gu ON gu.id = g.user_id
      WHERE g.event_id = e.id),
    '[]'::json
  ) AS guests
FROM cal_events e
JOIN users u ON u.id = e.owner_id;
  $view$;
END
$$;
