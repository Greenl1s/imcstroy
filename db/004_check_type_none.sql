-- ============================================================
--  Добавляет значение 'none' ("Не требуется") к типу check_type.
--  Раньше было только 'verification' / 'calibration'.
--
--  Внимание: ALTER TYPE ... ADD VALUE не может выполняться внутри
--  транзакции вместе с другими командами (в старых версиях PostgreSQL) —
--  выполняйте этот файл ОТДЕЛЬНО, одной командой, как показано ниже.
--
--  Запуск:
--    cat db/004_check_type_none.sql | docker compose exec -T db psql -U pribory -d pribory
--
--  (Если у вас уже есть файл с номером 004 — например, для миграции,
--  добавившей control_type — переименуйте этот в следующий свободный номер,
--  например 005_check_type_none.sql; сам SQL внутри от этого не меняется.)
-- ============================================================

ALTER TYPE check_type ADD VALUE IF NOT EXISTS 'none';
