-- ============================================================
--  Типовые задачи Planfix по стадиям теперь управляемый список
--  (как справочник организаций), а не зашитый в код константа —
--  добавленная вручную задача сохраняется и появляется у всех
--  последующих проектов на этой же стадии.
-- ============================================================

CREATE TABLE IF NOT EXISTS planfix_task_templates (
  id SERIAL PRIMARY KEY,
  stage TEXT NOT NULL CHECK (stage IN ('plan', 'active', 'control')),
  name TEXT NOT NULL,
  position INT NOT NULL DEFAULT 0,
  UNIQUE (stage, name)
);

