-- ============================================================
--  Единый вход (SSO) между ИСУ и «Учётом оборудования».
--
--  Личность пользователя (логин/пароль/роль) теперь целиком хранится
--  в базе "Учёта оборудования" — оттуда её и проверяют оба сайта.
--  Здесь, в ИСУ, остаются только СВОИ права на разделы (Инструменты/
--  База данных/Дела), привязанные к тому же самому числовому id
--  пользователя, что и в "Учёте оборудования".
--
--  Внешний ключ на users(id) здесь НЕ ставим — та таблица находится
--  в другой базе данных, PostgreSQL не умеет ссылаться между базами.
--  Целостность id поддерживается на уровне приложения (см. миграцию
--  migrate-users.mjs, которая сопоставляет старых fm_users с users
--  из "Учёта оборудования" по одинаковому логину).
-- ============================================================

CREATE TABLE IF NOT EXISTS fm_permissions (
  user_id INTEGER PRIMARY KEY,
  can_tools BOOLEAN NOT NULL DEFAULT false,
  can_db BOOLEAN NOT NULL DEFAULT false,
  can_cases BOOLEAN NOT NULL DEFAULT false
);
