/* ---------------- Роль руководителя ---------------- */

-- Инструкция раз за разом говорит «по решению руководителя»: отмена
-- активной экспертизы (п. 29.3), нестандартные случаи оплаты (п. 27.3),
-- завершение проекта (п. 28.1). В ИСУ такой роли не было.
--
-- Нарочно НЕ трогаем users.role: эта таблица общая с «Учётом
-- оборудования», и новое значение роли там отозвалось бы неизвестно как.
-- Руководитель — это отдельное право в наших собственных правах.
