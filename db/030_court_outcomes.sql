/* ---------------- История решений суда по проекту ---------------- */

CREATE TABLE IF NOT EXISTS case_court_events (
  id            SERIAL PRIMARY KEY,
  case_id       INTEGER NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  outcome_id    INTEGER,
  -- Название сохраняем снимком: справочник могут поправить, а запись в
  -- истории должна остаться читаемой такой, какой её сделали.
  outcome_name  TEXT NOT NULL,
  event_date    DATE NOT NULL,
  hearing_date  DATE,
  expertise_due DATE,
  note          TEXT,
  -- manual — вписал человек; kad — приедет из картотеки, когда подключим.
  source        TEXT NOT NULL DEFAULT 'manual',
  plan          JSONB,
  applied       BOOLEAN NOT NULL DEFAULT FALSE,
  applied_at    TIMESTAMPTZ,
  applied_by    INTEGER,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by    INTEGER
);

CREATE INDEX IF NOT EXISTS case_court_events_case_idx
  ON case_court_events (case_id, event_date DESC, id DESC);

