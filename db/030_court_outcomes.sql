  user_id   INTEGER PRIMARY KEY,
  can_tools BOOLEAN NOT NULL DEFAULT FALSE,
  can_db    BOOLEAN NOT NULL DEFAULT FALSE,
  can_cases BOOLEAN NOT NULL DEFAULT FALSE
);
ALTER TABLE fm_permissions ADD COLUMN IF NOT EXISTS can_manage BOOLEAN NOT NULL DEFAULT FALSE;

/* ---------------- Производственный календарь ---------------- */

-- Сроки в инструкции считаются в рабочих днях («+3 рабочих дня»,
-- «+1 рабочий день»). Суббота и воскресенье выходные всегда, а праздники
-- и переносы каждый год свои — они и лежат здесь.
CREATE TABLE IF NOT EXISTS work_calendar (
  day  DATE PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('holiday', 'workday')),
  note TEXT
);
COMMENT ON TABLE work_calendar IS
  'holiday — нерабочий день (праздник или перенос выходного); '
  'workday — рабочая суббота или воскресенье (отработка переноса).';

-- Нерабочие праздничные дни по статье 112 ТК РФ. Они одни и те же из
-- года в год, поэтому их можно завести сразу. ПЕРЕНОСЫ (когда праздник
-- выпал на выходной) устанавливаются постановлением правительства на
-- каждый год отдельно — их вносит администратор в разделе календаря.
