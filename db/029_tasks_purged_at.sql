-- Отметка о том, что задачи проекта стёрты вместе с ним из корзины.
--
-- Пока проект лежит в корзине, его задачи целы и возвращаются вместе с
-- ним. Очистка корзины необратима — там задачи удаляются насовсем, и
-- эта отметка нужна, чтобы потом отличить «задач у проекта не было» от
-- «задачи были и удалены вместе с проектом».
ALTER TABLE cases ADD COLUMN IF NOT EXISTS tasks_purged_at TIMESTAMPTZ;
