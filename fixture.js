// Восстанавливает содержимое /home/claude/test/storage до исходного набора
// папок и файлов, на который рассчитаны наборы тестов. Некоторые тесты
// (xss, trash-ui) намеренно портят/чистят хранилище — запускать перед ними.
const fs = require("fs");
const path = require("path");

const ROOT = "/home/claude/test/storage";

const DIRS = [
  "База данных/Оборудование/Поверки и Калибровки",
  // Папка экспертов: на ней проверяется заведение эксперта и приложения
  // в гарантийном письме. Сами эксперты заводятся ниже — им нужен ещё
  // и "Сведения.docx", иначе в форму ГП они не попадут.
  "База данных/Эксперты",
  "База данных/Отчёты/Июль",
  "Дела/А40-15789_ООО Стройинвест",
  "Дела/ЭКС.А40",
  // Папки стадий: на них проверяется деление списка на "Экспертизы" и
  // "Независимые исследования", как в Планфиксе.
  "Дела/01.Планы/ЭКС.Гараж (Талдом)/Планирование проекта/ГП",
  "Дела/01.Планы/ЭКС.Гараж (Талдом)/ЭКС.Гараж (Талдом)/Материалы",
  "Дела/01.Планы/НИ.Аммиак/Планирование проекта/ГП",
  "Дела/01.Планы/НИ.Конюшня/Планирование проекта/ГП",
  "Дела/03.Проекты на контроле/НИ.Барвиха/Планирование проекта/ГП",
  // Название без привычного префикса: по имени такой проект попадал в
  // «Прочее», хотя это экспертиза. На нём проверяется правка типа.
  "Дела/03.Проекты на контроле/ЭКСПЕРТИЗА НИЦ/Планирование проекта/ГП",
];
const FILES = {
  "База данных/Отчёты/акт.docx": "содержимое акта",
  "База данных/Отчёты/отчёт2.docx": "x",
  "База данных/Отчёты/Смета.xlsx": "цифры",
  "База данных/Отчёты/Июль/июльский.docx": "x",
  "База данных/Оборудование/Поверки и Калибровки/протокол.pdf": "x",
  "Дела/А40-15789_ООО Стройинвест/Определение суда.pdf": "x",
  "Дела/ЭКС.А40/Заключение эксперта.docx": "текст заключения",
};

fs.rmSync(ROOT, { recursive: true, force: true });
for (const d of DIRS) fs.mkdirSync(path.join(ROOT, d), { recursive: true });
for (const [f, content] of Object.entries(FILES)) fs.writeFileSync(path.join(ROOT, f), content);

// Пять экспертов со сведениями — на них рассчитаны наборы про форму ГП.
// Раньше этот список был захардкожен в самом стенде и не зависел от
// диска: проверить на нём заведение эксперта было нельзя. Теперь папки
// настоящие, и делает их тот же код, что и кнопка «Добавить эксперта».
const expertsLib = require("/home/claude/fm/src/experts.js");
const safeResolve = (rel) => path.join(ROOT, rel.replace(/^\/+/, ""));
for (const name of ["Гиясов Б.И", "Гололобов.П.В", "Давыдов.А.Е", "Коляскин.В.Ю", "Пантелеев.С.С"]) {
  const dir = safeResolve(expertsLib.expertPath(name));
  fs.mkdirSync(path.join(dir, expertsLib.ATTACH_DIRNAME), { recursive: true });
  fs.writeFileSync(
    path.join(dir, expertsLib.INFO_FILENAME),
    expertsLib.buildInfoDocx([`Эксперт ${name}`, "Образование: профильное", "Стаж: 10 лет"])
  );
}

// Файлы восстановили — надо восстановить и базу. Корзина и история живут
// в PostgreSQL, и записи, оставшиеся от предыдущего набора, ломали
// следующий: он ожидал пустую корзину, а видел чужие строки. Раньше это
// зависело от порядка запуска; теперь — нет.
(async () => {
  process.env.PGHOST = process.env.PGHOST || "/tmp";
  process.env.PGPORT = process.env.PGPORT || "5433";
  process.env.PGUSER = process.env.PGUSER || "pribory";
  // База та же, что у «Учёта»: на боевом сервере она одна на обе системы
// (общий контейнер db), и раздел «Оборудование» читает приборы прямо
// из неё. Стенд должен повторять эту схему, иначе проверять раскладку
// папок было бы не на чем.
process.env.PGDATABASE = process.env.PGDATABASE || "uchet";
  const { Pool } = require("/home/claude/fm/node_modules/pg");
  const pool = new Pool();
  try {
    await pool.query("TRUNCATE fm_trash, fm_events RESTART IDENTITY");
  } catch (err) {
    // Базы может не быть — тогда набор и так не запустится, а сообщение
    // об этом лучше получить от него, чем отсюда.
    console.log("база не очищена: " + err.message);
  } finally {
    await pool.end();
  }
  console.log("fixture restored: " + ROOT);
})();
