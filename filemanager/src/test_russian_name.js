const assert = require("assert");
const { declineFullName, declineFullNames, countForm } = require("./russianName");

const examples = [
  ["Базаев Кирилл Евгеньевич", "genitive", "Базаева Кирилла Евгеньевича"],
  ["Базаев Кирилл Евгеньевич", "dative", "Базаеву Кириллу Евгеньевичу"],
  ["Гололобов Пётр Валерьевич", "accusative", "Гололобова Петра Валерьевича"],
  ["Воровкин Павел Александрович", "instrumental", "Воровкиным Павлом Александровичем"],
  ["Иванова Анна Сергеевна", "genitive", "Ивановой Анны Сергеевны"],
  ["Иванова Анна Сергеевна", "dative", "Ивановой Анне Сергеевне"],
  ["Иванова Анна Сергеевна", "accusative", "Иванову Анну Сергеевну"],
  ["Сидоренко Мария Ильинична", "genitive", "Сидоренко Марии Ильиничны"],
  ["Челышков П.Д.", "genitive", "Челышкова П.Д."],
  ["Толстой Лев Николаевич", "dative", "Толстому Льву Николаевичу"],
  ["Петров-Сидоров Дмитрий Андреевич", "prepositional", "Петрове-Сидорове Дмитрии Андреевиче"],
  ["Кузнецова Наталья Игоревна", "instrumental", "Кузнецовой Натальей Игоревной"],
  ["Орлова Любовь Петровна", "accusative", "Орлову Любовь Петровну"],
  ["Шевченко Сергей Олегович", "genitive", "Шевченко Сергея Олеговича"],
];
for (const [source, gramCase, expected] of examples) {
  assert.strictEqual(declineFullName(source, gramCase), expected, `${source}, ${gramCase}`);
}
assert.strictEqual(
  declineFullNames(["Базаев Кирилл Евгеньевич", "Гололобов Пётр Валерьевич"], "accusative"),
  "Базаева Кирилла Евгеньевича и Гололобова Петра Валерьевича"
);
assert.strictEqual(countForm(1, "рабочий день", "рабочих дня", "рабочих дней"), "рабочий день");
assert.strictEqual(countForm(22, "рабочий день", "рабочих дня", "рабочих дней"), "рабочих дня");
assert.strictEqual(countForm(15, "рабочий день", "рабочих дня", "рабочих дней"), "рабочих дней");
const replacementSentence = `В связи с увольнением эксперта ${declineFullName("Базаев Кирилл Евгеньевич", "genitive")} ` +
  `прошу суд вместо ${declineFullName("Базаев Кирилл Евгеньевич", "genitive")} включить в группу экспертов ` +
  `${declineFullName("Гололобов Пётр Валерьевич", "accusative")}.`;
assert.strictEqual(replacementSentence,
  "В связи с увольнением эксперта Базаева Кирилла Евгеньевича прошу суд вместо " +
  "Базаева Кирилла Евгеньевича включить в группу экспертов Гололобова Петра Валерьевича.");
assert.strictEqual(
  `Выполнение экспертизы будет поручено эксперту ${declineFullName("Гололобов Пётр Валерьевич", "dative")}`,
  "Выполнение экспертизы будет поручено эксперту Гололобову Петру Валерьевичу"
);
console.log(`Проверено грамматических форм и фраз: ${examples.length + 6}`);
